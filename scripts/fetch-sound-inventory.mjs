/**
 * §38: build the ground truth of what the game can actually play.
 *
 * Downloads the same sample maps the engine loads at runtime and writes the
 * full list of sound names to src/audio/soundInventory.generated.ts, so tests
 * can prove that every sound the grammars emit really exists. A name that
 * looks plausible and is not there (RolandTR77) is silence, not an error —
 * which is exactly the failure this file exists to prevent.
 *
 * Run: npm run sounds:audit
 */
import { writeFileSync } from 'node:fs';

const MAPS = [
  'https://raw.githubusercontent.com/felixroos/dough-samples/main/tidal-drum-machines.json',
  'https://raw.githubusercontent.com/felixroos/dough-samples/main/vcsl.json',
  'https://raw.githubusercontent.com/felixroos/dough-samples/main/EmuSP12.json',
  'https://raw.githubusercontent.com/felixroos/dough-samples/main/Dirt-Samples.json',
  'https://raw.githubusercontent.com/felixroos/dough-samples/main/piano.json',
];

/** Strudel's built-in oscillators and noise colours need no sample map. */
const BUILT_IN = [
  'sine', 'triangle', 'square', 'sawtooth', 'supersaw', 'pulse',
  'white', 'pink', 'brown', 'crackle', 'sbd', 'bytebeat', 'z_sine', 'z_saw',
];

const names = new Set(BUILT_IN);

for (const url of MAPS) {
  const response = await fetch(url);
  if (!response.ok) {
    console.error(`FAILED ${response.status} ${url}`);
    process.exit(1);
  }
  const map = await response.json();
  for (const key of Object.keys(map)) {
    if (key.startsWith('_')) continue;
    names.add(key.toLowerCase());
  }
  console.log(`${url.split('/').pop()}: ${Object.keys(map).length} entries`);
}

const sorted = [...names].sort();
writeFileSync(
  new URL('../src/audio/soundInventory.generated.ts', import.meta.url),
  `// GENERATED by scripts/fetch-sound-inventory.mjs — do not edit by hand.
// The sounds the loaded sample maps actually provide (§38).
export const SOUND_INVENTORY: readonly string[] = ${JSON.stringify(sorted, null, 0)};
`,
);
console.log(`wrote ${sorted.length} sound names`);
